'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const b=require('../prototype/behavior-v116.js');
test('v99 defaults to neutral for unknown mood',()=>assert.deepEqual(b.profile('nope'),b.profile('neutral')));
test('v100 happy tails lively',()=>assert.equal(b.profile('happy').tail,'lively'));
test('v101 serious tails quiet',()=>assert.equal(b.profile('serious').tail,'still'));
test('v102 thinking tails calm',()=>assert.ok(b.profile('thinking').amplitude<b.profile('happy').amplitude));
test('v103 magical profile custom',()=>assert.equal(b.profile('magic').ear,4));
test('v104 reply classification concern',()=>assert.equal(b.classifyReply('Будь осторожна, это опасно'),'serious'));
test('v105 reply classification fox',()=>assert.equal(b.classifyReply('Мои девять хвостов'),'magic'));
test('v106 reply classification thought',()=>assert.equal(b.classifyReply('Давай подумаем'),'thinking'));
test('v107 reply classification positivity',()=>assert.equal(b.classifyReply('Очень рада'),'happy'));
test('v108 reply neutral fallback',()=>assert.equal(b.classifyReply('Слово'),'neutral'));
test('v109 blend endpoints',()=>{assert.equal(b.blend(2,10,0),2);assert.equal(b.blend(2,10,1),10);});
test('v110 blend rejects invalid ratio',()=>assert.throws(()=>b.blend(0,10,3),RangeError));
test('v111 controller initializes neutral',()=>assert.equal(b.create().mood,'neutral'));
test('v112 transitions target mood',()=>{const s=b.create();s.set('happy');assert.equal(s.mood,'happy');});
test('v113 finite progression',()=>{const s=b.create();s.set('happy');const p=s.step(.1);assert.ok(p.progress>0&&p.progress<1);});
test('v114 settled profile matches target',()=>{const s=b.create();s.set('happy');s.step(.5);assert.equal(s.step(0).amplitude,b.profile('happy').amplitude);});
test('v115 negative dt rejected',()=>assert.throws(()=>b.create().step(-.1),RangeError));
test('v116 reset clears state',()=>{const s=b.create();s.set('magic');s.reset();assert.equal(s.mood,'neutral');});
