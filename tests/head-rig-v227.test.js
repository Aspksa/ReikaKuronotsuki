'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),rig=require('../prototype/head-rig-v227.js');
test('head yaw clamps',()=>{assert.equal(rig.pose({yaw:90}).yaw,30);assert.equal(rig.pose({yaw:-99}).yaw,-30);});
test('head pitch clamps',()=>assert.equal(rig.pose({pitch:30}).pitch,20));
test('head roll clamps',()=>assert.equal(rig.pose({roll:-99}).roll,-20));
test('gaze horizontal clamps',()=>assert.equal(rig.pose({gazeX:99}).gazeX,12));
test('gaze vertical clamps',()=>assert.equal(rig.pose({gazeY:-99}).gazeY,-10));
test('default neutral',()=>assert.deepEqual(rig.pose(),{yaw:0,pitch:0,roll:0,gazeX:0,gazeY:0}));
test('transform finite and deterministic',()=>{const a=rig.transform({yaw:10,pitch:-3,roll:7});assert.equal(a,rig.transform({yaw:10,pitch:-3,roll:7}));assert.doesNotMatch(a,/NaN|Infinity/);});
test('head yaw changes transform',()=>assert.notEqual(rig.transform({yaw:10}),rig.transform({yaw:0})));
