'use strict';
const test=require('node:test'),assert=require('node:assert/strict');const v=require('../prototype/voice-persona-v134.js');
test('v117 trims input',()=>assert.equal(v.clean('  Привет  '),'Привет'));
test('v118 bounds text',()=>assert.equal(v.clean('a'.repeat(700)).length,500));
test('v119 gentle voice default',()=>assert.equal(v.profile('gentle').rate,1));
test('v120 playful voice faster',()=>assert.ok(v.profile('playful').rate>1));
test('v121 composed voice slower',()=>assert.ok(v.profile('composed').rate<1));
test('v122 invalid persona rejected',()=>assert.throws(()=>v.profile('admin'),RangeError));
test('v123 happy selects playful',()=>assert.equal(v.express('happy'),'playful'));
test('v124 serious selects composed',()=>assert.equal(v.express('serious'),'composed'));
test('v125 thinking selects composed',()=>assert.equal(v.express('thinking'),'composed'));
test('v126 magic selects playful',()=>assert.equal(v.express('magic'),'playful'));
test('v127 unknown emotion uses gentle',()=>assert.equal(v.express('nonsense'),'gentle'));
test('v128 bounded speech rate',()=>assert.throws(()=>v.normalize({rate:2}),RangeError));
test('v129 bounded speech pitch',()=>assert.throws(()=>v.normalize({pitch:0}),RangeError));
test('v130 invalid profile object',()=>assert.throws(()=>v.normalize(null),TypeError));
test('v131 preserves user-set rate',()=>assert.equal(v.normalize({style:'gentle',rate:1.2}).rate,1.2));
test('v132 estimates words',()=>assert.equal(v.sampleSpeech('  Раз два три  ').words,3));
test('v133 empty text duration deterministic',()=>assert.equal(v.sampleSpeech('').words,0));
test('v134 estimates finite duration',()=>assert.ok(Number.isFinite(v.sampleSpeech('Привет Рэйка').estimatedSeconds)));
